import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { resolveGitDirs } from "./git.mjs";

export const MARKER_START = "# --- BEGIN AGENTIC REPO EXCLUDES ---";
export const MARKER_END = "# --- END AGENTIC REPO EXCLUDES ---";

// Kit-owned directories that keep growing after initialization (new wiki pages,
// ADRs, annealing proposals), so they are excluded as whole directories.
export const GROWTH_DIRECTORIES = [
  "/.agents/",
  "/docs/raw/",
  "/docs/wiki/",
  "/docs/adr/",
  "/docs/product/",
  "/docs/specs/",
  "/docs/templates/",
];

// Fallback only, for repositories without a scaffold.lock. Patterns are anchored to
// the repository root so nested files with the same name are never hidden.
export const DEFAULT_EXCLUDE_PATTERNS = [
  ...GROWTH_DIRECTORIES,
  "/AGENTS.md",
  "/THIRD_PARTY_NOTICES.md",
  "/scaffold.yaml",
  "/scaffold.lock",
  "/CLAUDE.md",
  "/.claude/agents/",
  "/.codex/agents/",
  "/GEMINI.md",
  "/.gemini/agents/",
  "/.github/copilot-instructions.md",
  "/.github/agents/",
  "/.cursor/rules/agentic-kernel.mdc",
  "/opencode.json",
  "/.opencode/agents/",
  "/.kiro/steering/agentic-kernel.md",
];

// Derives the exclusion patterns from the files the kit actually manages, so the
// list can never drift from the generated adapters.
export async function managedExcludePatterns(cwd) {
  let lock;
  try {
    lock = JSON.parse(await readFile(path.join(cwd, "scaffold.lock"), "utf8"));
  } catch {
    return null;
  }
  if (!Array.isArray(lock?.managedFiles)) return null;
  const patterns = new Set([...GROWTH_DIRECTORIES, "/scaffold.lock"]);
  for (const entry of lock.managedFiles) {
    if (typeof entry?.path !== "string") continue;
    const anchored = `/${entry.path}`;
    if (!GROWTH_DIRECTORIES.some((directory) => anchored.startsWith(directory))) patterns.add(anchored);
  }
  return [...GROWTH_DIRECTORIES, ...[...patterns].filter((pattern) => !GROWTH_DIRECTORIES.includes(pattern)).sort()];
}

export async function resolveGitExcludePath(cwd) {
  const dirs = await resolveGitDirs(cwd);
  return dirs ? path.join(dirs.commonDir, "info", "exclude") : null;
}

// Before ADR-0026 the block went to a linked worktree's own info/exclude, which Git
// never reads. Its presence still records that the owner chose local exclusions.
async function legacyExcludePath(cwd) {
  const dirs = await resolveGitDirs(cwd);
  return dirs && dirs.gitDir !== dirs.commonDir ? path.join(dirs.gitDir, "info", "exclude") : null;
}

async function readManagedPatterns(file) {
  let content;
  try {
    content = await readFile(file, "utf8");
  } catch {
    return null;
  }
  const startIndex = content.indexOf(MARKER_START);
  const endIndex = content.indexOf(MARKER_END);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) return null;
  return content
    .slice(startIndex + MARKER_START.length, endIndex)
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
}

async function removeLegacyBlock(cwd) {
  const legacyPath = await legacyExcludePath(cwd);
  if (!legacyPath || (await readManagedPatterns(legacyPath)) === null) return false;
  const cleaned = stripManagedBlock(await readFile(legacyPath, "utf8"));
  await writeFile(legacyPath, cleaned.length > 0 ? `${cleaned}\n` : "", "utf8");
  return true;
}

function stripManagedBlock(content) {
  const startIndex = content.indexOf(MARKER_START);
  const endIndex = content.indexOf(MARKER_END);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    return content.trim();
  }
  const before = content.slice(0, startIndex).trimEnd();
  const after = content.slice(endIndex + MARKER_END.length).trimStart();
  const combined = [before, after].filter(Boolean).join("\n\n");
  return combined.trim();
}

export async function applyGitExclude(cwd, customPatterns = null) {
  const excludePath = await resolveGitExcludePath(cwd);
  if (!excludePath) {
    return { ok: false, reason: "no-git", path: null };
  }

  let existing = "";
  try {
    existing = await readFile(excludePath, "utf8");
  } catch {
    existing = "";
  }

  const cleaned = stripManagedBlock(existing);
  const patterns = customPatterns && customPatterns.length > 0
    ? customPatterns
    : (await managedExcludePatterns(cwd)) ?? DEFAULT_EXCLUDE_PATTERNS;

  const blockLines = [
    MARKER_START,
    "# Generated by agentic-repo-kit. Managed automatically.",
    ...patterns,
    MARKER_END,
  ];

  const newContent = cleaned.length > 0
    ? `${cleaned}\n\n${blockLines.join("\n")}\n`
    : `${blockLines.join("\n")}\n`;

  await mkdir(path.dirname(excludePath), { recursive: true });
  await writeFile(excludePath, newContent, "utf8");
  await removeLegacyBlock(cwd);

  return { ok: true, path: excludePath, patterns };
}

export async function removeGitExclude(cwd) {
  const excludePath = await resolveGitExcludePath(cwd);
  if (!excludePath) {
    return { ok: false, reason: "no-git", path: null };
  }
  const legacyRemoved = await removeLegacyBlock(cwd);

  let existing = "";
  try {
    existing = await readFile(excludePath, "utf8");
  } catch {
    return { ok: true, path: excludePath, removed: legacyRemoved };
  }

  const cleaned = stripManagedBlock(existing);
  const newContent = cleaned.length > 0 ? `${cleaned}\n` : "";

  await writeFile(excludePath, newContent, "utf8");
  return { ok: true, path: excludePath, removed: true };
}

// `patterns` are the exclusions Git applies; `legacy` reports a block that an
// earlier version left where Git does not read it, so `update` moves it.
export async function inspectGitExclude(cwd) {
  const excludePath = await resolveGitExcludePath(cwd);
  if (!excludePath) {
    return { ok: false, reason: "no-git", active: false, legacy: false, patterns: [] };
  }
  const patterns = await readManagedPatterns(excludePath);
  const legacyPath = await legacyExcludePath(cwd);
  const legacy = legacyPath ? (await readManagedPatterns(legacyPath)) !== null : false;
  return { ok: true, path: excludePath, active: patterns !== null, legacy, patterns: patterns ?? [] };
}
