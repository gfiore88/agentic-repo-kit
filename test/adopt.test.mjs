import test from "node:test";
import assert from "node:assert/strict";
import { access, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { parseArgs } from "../plugins/agentic-repo/scripts/lib/args.mjs";
import { runCli } from "../plugins/agentic-repo/scripts/lib/cli.mjs";
import { parseScaffoldYaml } from "../plugins/agentic-repo/scripts/lib/lock.mjs";

async function run(argv) {
  const out = [];
  const err = [];
  const originalOut = process.stdout.write;
  const originalErr = process.stderr.write;
  process.stdout.write = (chunk) => (out.push(String(chunk)), true);
  process.stderr.write = (chunk) => (err.push(String(chunk)), true);
  try {
    const code = await runCli(argv);
    return { code, out: out.join(""), err: err.join("") };
  } finally {
    process.stdout.write = originalOut;
    process.stderr.write = originalErr;
  }
}

async function exists(target) {
  try { await access(target); return true; } catch { return false; }
}

async function tempDir(t) {
  const dir = await mkdtemp(path.join(os.tmpdir(), "agentic-repo-adopt-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  return dir;
}

async function initialized(t, ...flags) {
  const dir = await tempDir(t);
  assert.equal((await run(["init", "--yes", "--cwd", dir, ...flags])).code, 0);
  return dir;
}

async function append(file, text) {
  await writeFile(file, `${await readFile(file, "utf8")}${text}`, "utf8");
}

// A kernel generated by an older kit version and customized by its owner, whose
// scaffold.lock and scaffold.yaml were never committed and are gone.
async function lostLockRepository(t) {
  const dir = await initialized(t, "--runtime", "github-copilot");
  await append(path.join(dir, "AGENTS.md"), "\n## Project rules\n\n- Keep the public API stable.\n");
  await writeFile(path.join(dir, ".agents/registry.md"), "# Registry from an older kit version\n", "utf8");
  await append(path.join(dir, "docs/wiki/log.md"), "\n- Entry the update must keep.\n");
  await rm(path.join(dir, "scaffold.lock"));
  await rm(path.join(dir, "scaffold.yaml"));
  return dir;
}

test("update without a lock or kernel files still points to init", async (t) => {
  const dir = await tempDir(t);
  const result = await run(["update", "--yes", "--cwd", dir]);
  assert.equal(result.code, 1);
  assert.match(result.err, /scaffold\.lock not found; this repository was not initialized by agentic-repo-kit\. Run `npx agentic-repo-kit init` first/);
  assert.equal(await exists(path.join(dir, "AGENTS.md")), false);
});

test("update points a kernel without a lock to restore or adopt, not to init", async (t) => {
  const dir = await lostLockRepository(t);
  const agents = await readFile(path.join(dir, "AGENTS.md"), "utf8");
  const result = await run(["update", "--yes", "--cwd", dir]);
  assert.equal(result.code, 1);
  assert.match(result.err, /scaffold\.lock not found, but kernel files exist \(AGENTS\.md, \.agents\/registry\.md\)/);
  assert.match(result.err, /Restore scaffold\.lock from version control/);
  assert.match(result.err, /`npx agentic-repo-kit update --adopt --runtime <ids\|none>`/);
  assert.match(result.err, /never initialized this repository, run `npx agentic-repo-kit init` instead/);
  assert.equal(await readFile(path.join(dir, "AGENTS.md"), "utf8"), agents);
  assert.equal(await exists(path.join(dir, "scaffold.lock")), false);

  const configured = await initialized(t, "--runtime", "none");
  await rm(path.join(configured, "scaffold.lock"));
  const hint = await run(["update", "--cwd", configured]);
  assert.match(hint.err, /run `npx agentic-repo-kit update --adopt`:/, "scaffold.yaml supplies the runtimes");
});

test("update reports an invalid or unreadable lock instead of a missing one", async (t) => {
  const dir = await initialized(t, "--runtime", "none");
  const lockPath = path.join(dir, "scaffold.lock");
  const lock = await readFile(lockPath, "utf8");
  const conflicted = `<<<<<<< HEAD\n${lock}=======\n${lock}>>>>>>> theirs\n`;
  await writeFile(lockPath, conflicted, "utf8");
  const invalid = await run(["update", "--yes", "--cwd", dir]);
  assert.equal(invalid.code, 1);
  assert.match(invalid.err, /scaffold\.lock is not a valid lock \(.+\)\. Restore it from version control, for example after a merge conflict/);
  assert.doesNotMatch(invalid.err, /not found/);
  assert.equal(invalid.err.trimEnd().includes("\n"), false, "the parse error stays on one line");
  assert.equal(await readFile(lockPath, "utf8"), conflicted);

  await writeFile(lockPath, "[]\n", "utf8");
  assert.match((await run(["update", "--yes", "--cwd", dir])).err, /not a valid lock \(not a JSON object\)/);

  await rm(lockPath);
  await mkdir(lockPath);
  const unreadable = await run(["update", "--yes", "--cwd", dir]);
  assert.equal(unreadable.code, 1);
  assert.match(unreadable.err, /cannot read scaffold\.lock \(.+\)\. Fix its permissions, or restore it from version control/);
});

test("doctor reports the lock state and the next step", async (t) => {
  const dir = await lostLockRepository(t);
  const missing = await run(["doctor", "--json", "--cwd", dir]);
  assert.equal(missing.code, 1);
  const payload = JSON.parse(missing.out);
  assert.equal(payload.lockState, "missing");
  assert.deepEqual(payload.missing, ["scaffold.lock"]);
  assert.match(payload.hint, /update --adopt --runtime <ids\|none>/);

  await writeFile(path.join(dir, "scaffold.lock"), "<<<<<<< HEAD\n", "utf8");
  const invalid = await run(["doctor", "--cwd", dir]);
  assert.equal(invalid.code, 1);
  assert.match(invalid.out, /^Missing: 0; divergent: 0$/m);
  assert.match(invalid.out, /^Lock: scaffold\.lock is not a valid lock/m);
  assert.match(invalid.out, /^Next step: Restore it from version control/m);
});

test("update --adopt reports every differing kernel file as a conflict and writes nothing", async (t) => {
  const dir = await lostLockRepository(t);
  const agents = await readFile(path.join(dir, "AGENTS.md"), "utf8");
  const result = await run(["update", "--adopt", "--yes", "--json", "--runtime", "github-copilot", "--cwd", dir]);
  assert.equal(result.code, 1);
  const plan = JSON.parse(result.out);
  assert.equal(plan.adopt, true);
  assert.deepEqual([...plan.conflicts].sort(), [".agents/registry.md", "AGENTS.md"]);
  assert.ok(plan.preserved.includes("docs/wiki/log.md"));
  assert.deepEqual(plan.removed, []);
  assert.equal(await exists(path.join(dir, "scaffold.lock")), false);
  assert.equal(await exists(path.join(dir, "scaffold.yaml")), false);
  assert.equal(await readFile(path.join(dir, "AGENTS.md"), "utf8"), agents);

  const text = await run(["update", "--adopt", "--dry-run", "--runtime", "github-copilot", "--cwd", dir]);
  assert.match(text.out, /^Adoption: no scaffold\.lock/m);
  assert.match(text.out, /conflict \(differs from this version\): AGENTS\.md/);
  assert.match(text.out, /cannot tell its older files from your edits/);
});

test("update --adopt --force adopts the kernel and keeps user-owned files", async (t) => {
  const dir = await lostLockRepository(t);
  const result = await run(["update", "--adopt", "--force", "--yes", "--runtime", "github-copilot", "--cwd", dir]);
  assert.equal(result.code, 0);
  assert.match(result.out, /Kernel adoption complete/);
  const lock = JSON.parse(await readFile(path.join(dir, "scaffold.lock"), "utf8"));
  assert.deepEqual(lock.runtimes, ["github-copilot"]);
  assert.match(await readFile(path.join(dir, "scaffold.yaml"), "utf8"), /^ {4}- github-copilot$/m);
  assert.doesNotMatch(await readFile(path.join(dir, "AGENTS.md"), "utf8"), /Project rules/);
  assert.match(await readFile(path.join(dir, "docs/wiki/log.md"), "utf8"), /Entry the update must keep/);
  assert.equal((await run(["doctor", "--cwd", dir])).code, 0);
  assert.equal((await run(["update", "--yes", "--cwd", dir])).code, 0, "the new lock drives later updates");
});

test("update --adopt reads the configuration from scaffold.yaml and regenerates it", async (t) => {
  const dir = await initialized(t, "--runtime", "claude-code", "--enforce", "ci");
  await rm(path.join(dir, "scaffold.lock"));
  // The format written before 0.7.0 (no profile line), with CRLF line endings.
  await writeFile(path.join(dir, "scaffold.yaml"), "version: 1\r\nenforcement: ci\r\ncompatibility:\r\n  detection: assisted\r\n  runtimes:\r\n    - claude-code\r\n", "utf8");
  const result = await run(["update", "--adopt", "--yes", "--json", "--cwd", dir]);
  assert.equal(result.code, 0);
  const plan = JSON.parse(result.out);
  assert.deepEqual([plan.runtimes, plan.enforcement, plan.profile], [["claude-code"], "ci", "full"]);
  assert.deepEqual(plan.conflicts, []);
  assert.ok(plan.updated.includes("scaffold.yaml"), "scaffold.yaml is regenerated, not a conflict");
  assert.match(await readFile(path.join(dir, "scaffold.yaml"), "utf8"), /^profile: full$/m);
  assert.equal(JSON.parse(await readFile(path.join(dir, "scaffold.lock"), "utf8")).enforcement, "ci");
});

test("update --adopt is refused when a lock exists or the runtimes are unknown", async (t) => {
  const dir = await initialized(t, "--runtime", "none");
  const withLock = await run(["update", "--adopt", "--yes", "--cwd", dir]);
  assert.equal(withLock.code, 1);
  assert.match(withLock.err, /already has scaffold\.lock; run update without --adopt/);

  const lockPath = path.join(dir, "scaffold.lock");
  await writeFile(lockPath, "<<<<<<< HEAD\n", "utf8");
  const damaged = await run(["update", "--adopt", "--yes", "--runtime", "none", "--cwd", dir]);
  assert.equal(damaged.code, 1);
  assert.match(damaged.err, /--adopt never replaces an existing lock/);
  assert.equal(await readFile(lockPath, "utf8"), "<<<<<<< HEAD\n");

  await rm(lockPath);
  await rm(path.join(dir, "scaffold.yaml"));
  const unknown = await run(["update", "--adopt", "--yes", "--cwd", dir]);
  assert.equal(unknown.code, 1);
  assert.match(unknown.err, /Pass --runtime <ids\|none>/);
  assert.equal(await exists(lockPath), false);

  assert.throws(() => parseArgs(["init", "--adopt"]), /--adopt applies only to update/);
});

test("update --adopt --dry-run writes nothing", async (t) => {
  const dir = await initialized(t, "--runtime", "none");
  await rm(path.join(dir, "scaffold.lock"));
  await rm(path.join(dir, "scaffold.yaml"));
  const result = await run(["update", "--adopt", "--dry-run", "--runtime", "none", "--cwd", dir]);
  assert.equal(result.code, 0);
  assert.match(result.out, /create: scaffold\.lock/);
  assert.equal(await exists(path.join(dir, "scaffold.lock")), false);
  assert.equal(await exists(path.join(dir, "scaffold.yaml")), false);
});

test("parseScaffoldYaml reads every scaffold.yaml format the kit has written", () => {
  assert.deepEqual(
    parseScaffoldYaml("version: 1\ncompatibility:\n  detection: assisted\n  runtimes: []\n"),
    { runtimes: [], enforcement: null, profile: null },
  );
  assert.deepEqual(
    parseScaffoldYaml("version: 1\nenforcement: hooks\nprofile: core\ncompatibility:\n  detection: assisted\n  runtimes:\n    - claude-code\n    - copilot\n"),
    { runtimes: ["claude-code", "github-copilot"], enforcement: "hooks", profile: "core" },
  );
  assert.equal(parseScaffoldYaml("version: 1\ncompatibility:\n  runtimes:\n    - unknown-runtime\n"), null);
  assert.equal(parseScaffoldYaml("version: 1\n"), null);
});
